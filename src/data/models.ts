export function costTierColor(tier: CostTier): string {
  switch (tier) {
    case "free":
      return "var(--color-cost-1)";
    case "$":
      return "var(--color-cost-1)";
    case "$$":
      return "var(--color-cost-2)";
    case "$$$":
      return "var(--color-cost-3)";
    case "$$$+":
      return "var(--color-cost-4)";
  }
}
